#include <iostream>
#include <algorithm>
#include <string>
#include <vector>
using namespace std;

int p012() {
    int N=0;
    cout << "# of students:\n";
    cin >> N;
    string name;
    int grade=0;
    int sum=0;
    vector<int> vec;
    for (int i=0;i<N;i++) {
        cout << "name & score of student :";
        cin >> name >> grade;
        vec.push_back(grade);
        sum += grade;
    }
    sort(vec.begin(),vec.end());
    cout << "The average score of the students is " << sum/N << "\n";
    cout << "The student with the highest score is " << vec[N-1] << "\n";
}

























