#아이디어: 일찍 끝나는 회의를 고르면 그 뒤에 배치할 여유 공간이 최대
#즉, 1.먼저 전체 회의들 중에서 회의 일찍 끝나는 순서대로 나열한다
# 2. 이전 회의의 끝 <= 다음회의 시작으로만 카운팅하고 진행

#그리디는 그때 그때 최선의 수만 보면서 가는 것(그때 그때 단편적으로 최선으로만 판단)

import sys

n = int(input())
pairs = []

currenttime: int = 0
ans: int = 0

for _ in range(n):
    a, b = map(int, sys.stdin.readline().rstrip().split()) #rstrip()은 받은 string의 오른쪽제거
    pairs.append((a, b))

pairs.sort(key=lambda x: (x[1], x[0])) #이게 람다로 끝나는 시간(인덱스1)대로 pair의 튜플들을 정렬해주는 것이고 끝나는 시간(인덱스1)이 같다면 시작하는 시간(인덱스0)으로 정렬한다는 것

for start, end in pairs: #여기서 start와 end는 현재 회의 진행 상황임
    if currenttime <= start:
        ans+=1
        currenttime = end

print(ans)

