//clear()를 활용한 그리디(Greedy) 탐색: 후보를 찾을 때마다 "이게 제일 빠른가?"를 리스트 전체에 대해 재검사하지 않고, 탐색 도중 더 빠른 문자가 나타나면 가차 없이 기존 리스트를 비워버리는 방식으로 속도를 비약적으로 높였습니다.
//sort -> unique -> erase 기법: C++로 알고리즘을 풀 때 set 대신 벡터 중복을 제거하는 가장 교과서적이고 강력한 패턴입니다. 꼭 손에 익혀두시는 것을 권장합니다.



