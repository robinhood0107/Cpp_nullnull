#include <iostream>
#include <vector>
#include <string>
#include <algorithm>

using namespace std;

// [전역 변수 선언]
// 최대 문자열 길이 1000 + 점프 가능 거리 k(최대 10)의 여유를 두어 1015로 설정합니다.
// 전역(Global) 공간에 배열을 선언하면 모든 값이 자동으로 0으로 초기화되므로 편리합니다.
// dp[i][j] : S의 i번째 인덱스, T의 j번째 인덱스에서 '시작'하는 최장 공통 준문자열의 길이
int dp[1015][1015]; 

int main() {
    // [입출력 최적화] 
    // C++의 cin/cout 속도를 C의 scanf/printf 수준으로 끌어올리기 위한 필수 코드입니다.
    ios_base::sync_with_stdio(false); 
    cin.tie(NULL);

    int k;
    // k값을 입력받지 못하면(EOF 등) 프로그램을 종료합니다.
    if (!(cin >> k)) return 0;
    
    string S, T; 
    cin >> S >> T;

    int n = S.length();
    int m = T.length();
    
    // 전체 DP 테이블에서 가장 긴 LCQ의 길이를 저장할 변수입니다.
    int max_len = 0;

    // =========================================================================
    // 1단계: 역방향 DP 테이블 채우기
    // 앞에서부터 찾으면 동률일 때 사전식을 비교하기 어렵기 때문에,
    // 문자열의 '끝'에서부터 '처음' 방향으로 거꾸로 계산해 나갑니다.
    // =========================================================================
    for (int i = n - 1; i >= 0; i--) {
        for (int j = m - 1; j >= 0; j--) {
            
            // 두 문자가 같을 때만 준문자열을 이어나갈 수 있습니다.
            if (S[i] == T[j]) {
                int nxt_len = 0; // 다음으로 이어나갈 수 있는 최대 길이를 임시 저장
                
                // [인덱스 바운더리 처리]
                // 현재 위치(i, j)에서 점프할 수 있는 최대 한계선을 계산합니다.
                // 배열 범위를 벗어나지 않도록 (문자열 끝 인덱스)와 (k칸 점프한 인덱스) 중 작은 값을 택합니다.
                int max_r = min(i + k + 1, n - 1);
                int max_c = min(j + k + 1, m - 1);
                
                // 현재 좌표 (i, j)의 바로 다음(+1)부터 점프 가능 한계선까지 탐색합니다.
                for (int r = i + 1; r <= max_r; r++) {
                    for (int c = j + 1; c <= max_c; c++) {
                        // 탐색 범위 내에서 가장 긴 준문자열의 길이를 찾습니다.
                        if (dp[r][c] > nxt_len) {
                            nxt_len = dp[r][c];
                        }
                    }
                }
                
                // 현재 문자가 같으므로 (+1), 그 뒤로 이어나갈 수 있는 최대 길이(nxt_len)를 더합니다.
                dp[i][j] = nxt_len + 1;
                
                // 전체 테이블을 순회하며 가장 긴 길이(max_len)를 실시간으로 갱신해둡니다.
                if (dp[i][j] > max_len) {
                    max_len = dp[i][j];
                }
            }
        }
    }

    // =========================================================================
    // 2단계: 최장 길이(max_len)를 가지는 시작점 찾기 (사전식 순서 고려)
    // =========================================================================
    char min_c = 127; // 아스키코드 최댓값(대략 127)으로 초기화하여 어떤 문자보다도 크게 설정합니다.
    vector<pair<int, int>> q; // 탐색을 시작할 후보 좌표들을 담을 벡터입니다.
    
    // 테이블 전체를 순회하며 시작점을 찾습니다.
    for (int i = 0; i < n; i++) {
        for (int j = 0; j < m; j++) {
            
            // 길이가 max_len 이면서, 사전식으로 기존 발견된 문자보다 작거나 같은 경우
            if (dp[i][j] == max_len && S[i] <= min_c) {
                
                // 만약 완전히 더 빠른 문자를 발견했다면?
                if (S[i] < min_c) { 
                    min_c = S[i]; // 기준 문자를 갱신하고
                    q.clear();    // 이전에 저장해둔 느린 문자들의 좌표는 싹 비워버립니다.
                }
                
                // 현재 좌표를 후보군에 추가합니다. (같은 문자일 경우 계속 누적됨)
                q.push_back({i, j});
            }
        }
    }

    // =========================================================================
    // 3단계: 사전식 역추적 (Traceback / BFS)
    // =========================================================================
    string ans = ""; // 최종 정답이 담길 문자열
    
    // 남은 찾아야 할 길이가 0이 될 때까지 반복합니다.
    while (max_len > 0) {
        
        // q에 들어있는 좌표들은 '모두 동일한 문자'를 가리키고 있습니다. (위에서 그렇게 걸러냈으므로)
        // 따라서 아무 좌표나(여기서는 0번째) 선택해서 문자를 정답에 붙여줍니다.
        ans += S[q[0].first];
        
        // 하나를 찾았으므로 찾아야 할 길이를 1 줄입니다. 0이 되면 즉시 탈출합니다.
        if (--max_len == 0) break;

        vector<pair<int, int>> nxt_q; // 다음 길이(max_len - 1)에 해당하는 후보들을 담을 새 벡터
        char nxt_c = 127;             // 다음 후보들 중 가장 빠른 문자를 판별하기 위한 기준값

        // 현재 가지고 있는 후보 좌표들을 모두 순회하며 다음 단계로 뻗어나갑니다.
        for (const auto& p : q) {
            int r = p.first;  // 현재 후보의 S쪽 인덱스
            int c = p.second; // 현재 후보의 T쪽 인덱스
            
            // 다음 점프 가능 한계선 계산
            int max_r = min(r + k + 1, n - 1);
            int max_c = min(c + k + 1, m - 1);

            // 점프 가능 범위 탐색
            for (int nr = r + 1; nr <= max_r; nr++) {
                for (int nc = c + 1; nc <= max_c; nc++) {
                    
                    // 다음 좌표의 길이가 우리가 찾는 길이(max_len)와 일치하고,
                    // 문자가 현재까지 찾은 다음 문자(nxt_c)보다 작거나 같다면
                    if (dp[nr][nc] == max_len && S[nr] <= nxt_c) {
                        
                        // 더 빠른 문자를 발견했다면 싹 비우고 새출발
                        if (S[nr] < nxt_c) { 
                            nxt_c = S[nr]; 
                            nxt_q.clear(); 
                        }
                        
                        // 후보 좌표로 등록
                        nxt_q.push_back({nr, nc});
                    }
                }
            }
        }

        // [핵심 최적화: 중복 좌표 제거]
        // 여러 출발점에서 같은 도착점을 가리켜 중복 좌표가 엄청나게 쌓일 수 있습니다. (메모리 초과 원인)
        // 1. 좌표들을 정렬(sort)합니다.
        sort(nxt_q.begin(), nxt_q.end());
        // 2. unique 함수를 써서 연속된 중복 원소들을 뒤로 밀어내고, erase로 그 쓰레기값들을 잘라냅니다.
        nxt_q.erase(unique(nxt_q.begin(), nxt_q.end()), nxt_q.end());
        
        // [C++11 문법: move semantics]
        // nxt_q에 있는 데이터를 q로 복사(Copy)하는 것이 아니라,
        // 소유권 자체를 넘겨버려(Move) 불필요한 배열 복사 시간을 0으로 만듭니다.
        q = move(nxt_q); 
    }

    // 최종적으로 완성된 사전식 최장 공통 준문자열 출력
    cout << ans << "\n";
    
    return 0;
}



